-- Candidate replacements proposed for a retired name. Several candidates per retired name;
-- ischosen marks the one adopted, which is then mirrored into typhoonnames.replacementname.
CREATE TABLE suggestednames (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nameid bigint NOT NULL,
    replacementname character varying(10) NOT NULL,
    meaning character varying(255) DEFAULT NULL,
    ischosen boolean DEFAULT false NOT NULL,
    image character varying(255) DEFAULT NULL,
    imageauthor character varying,
    imagesourceurl character varying,
    imagelicenseid smallint,
    CONSTRAINT suggestednames_ibfk_1 FOREIGN KEY (nameid)
        REFERENCES typhoonnames(id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT suggestednames_imagelicenseid_fkey FOREIGN KEY (imagelicenseid)
        REFERENCES imagelicenses(id)
);

CREATE INDEX idx_17771_nameid ON suggestednames USING btree (nameid);

