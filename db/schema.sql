-- Every name that has ever held a position, current or retired. A position accumulates rows
-- over time: the name in rotation today plus each name that was retired out of that slot.
-- isretired distinguishes them.
CREATE TABLE typhoonnames (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(10) NOT NULL,
    meaning character varying(255) NOT NULL,
    tag character varying(40) NOT NULL,             -- category of the meaning, e.g. "Animal", "Flower"
    "position" integer NOT NULL,
    isretired boolean DEFAULT false NOT NULL,
    -- True once a replacement name has actually been selected; a name can be retired
    -- while the committee is still deciding, in which case suggestednames holds the candidates.
    isreplaced boolean DEFAULT false NOT NULL,
    replacementname character varying(10),
    note text,
    language character varying(20) NOT NULL,
    lastyear integer,                               -- final season the name was used; NULL while in rotation
    image character varying(255) DEFAULT NULL,
    description character varying(255),
    imageauthor character varying,
    imagesourceurl character varying,
    imagelicenseid smallint,
    ipa text DEFAULT 'NULL',                        -- default is the literal string 'NULL', not SQL NULL
    originaltext text,                              -- name in its native script, e.g. ヤギ
    pronunciationfile text,                         -- filename under public/, e.g. "Yagi.mp3"
    retirementreason typhoonnames_retirementreason,
    CONSTRAINT typhoonnames_retirementreason_requires_retired
        CHECK ((retirementreason IS NULL) = (NOT isretired)),
    CONSTRAINT typhoonnames_ibfk_1 FOREIGN KEY ("position")
        REFERENCES positions(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT typhoonnames_imagelicenseid_fkey FOREIGN KEY (imagelicenseid)
        REFERENCES imagelicenses(id)
);

