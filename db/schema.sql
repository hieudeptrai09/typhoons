-- One row per named storm occurrence. Joined to a name by position + name rather than by a
-- name id, since a position's storms span both its current and its retired names.
CREATE TABLE storms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "position" integer NOT NULL,
    name character varying(20) NOT NULL,
    intensity storms_intensity NOT NULL,
    map character varying(200) DEFAULT NULL,        -- track map URL
    year integer NOT NULL,
    isstrongest boolean DEFAULT false NOT NULL,     -- strongest storm to carry this name
    -- JTWC designation, number plus basin letter, e.g. '12W'. The letter is the basin the
    -- storm formed in, not its naming agency: Li 1994 and Nolo 2026 sit under CPHC (141) but
    -- read 'E'. Set even for a few 'MD' storms, which the JTWC numbered in post-season
    -- reanalysis without ever having tracked them live.
    jtwcdesignation character(3),
    -- JMA international number, "YYnn" for the nn-th storm of season YY, e.g. '2411' for
    -- Yagi 2024. Text, not integer, so the 2000-2009 seasons keep their leading zero ('0919').
    -- NULL for storms that entered the basin already named by another agency, which JMA
    -- numbers only if they are still at tropical-storm strength on arrival.
    jmanumber character(4) UNIQUE,
    isfirst boolean DEFAULT false NOT NULL,         -- first storm of its season
    islast boolean DEFAULT false NOT NULL,          -- last storm of its season
    startdate date NOT NULL,
    enddate date,
    CONSTRAINT storms_date_order_check
        CHECK (enddate IS NULL OR enddate >= startdate),
    CONSTRAINT storms_jtwcdesignation_format_check
        CHECK (jtwcdesignation ~ '^[0-9]{2}[WECB]$'),
    CONSTRAINT storms_ibfk_1 FOREIGN KEY ("position")
        REFERENCES positions(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX idx_17761_position ON storms USING btree ("position");

