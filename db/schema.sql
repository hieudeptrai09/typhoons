-- The 140 slots of the Western Pacific naming list. A position is a fixed slot in the
-- rotation, owned by one contributing country. Both typhoonnames and storms hang off it,
-- which is how a storm gets its country without duplicating it per row.
-- Positions 141-143 sit outside the list: they stand for the agency that named a storm in
-- another basin (CPHC, NHC, IMD) before it crossed into the western Pacific.
CREATE TABLE positions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country character varying(20) NOT NULL
);

